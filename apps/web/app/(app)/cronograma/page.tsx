import Link from 'next/link';
import {
  BookOpen,
  CalendarClock,
  CalendarDays,
  Check,
  ChevronLeft,
  ChevronRight,
  Clock,
  RotateCcw,
  Settings2,
  Sparkles,
  SkipForward,
  Target,
  Trash2,
} from 'lucide-react';
import {
  STUDY_SESSION_STATUS_LABELS,
  WEEKDAY_SHORT_LABELS,
  type StudySessionItem,
} from '@painel/shared';
import {
  useAvailability,
  useCompleteStudySession,
  useDeleteStudySession,
  useReopenStudySession,
  useSkipStudySession,
  useStudyPlanSummary,
  useStudySessions,
} from '@/hooks/use-study-plan';
import { Button } from '@/components/ui/button';
